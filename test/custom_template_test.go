package test

import (
	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"

	. "github.com/ArtHustle/mock_gen"
)

// Custom templates receive a MockData value and produce arbitrary Go output
// (run through gofmt). These tests focus on the *extension API* — what
// fields/types template authors can rely on. The default template's own
// shape is exercised by shape_test.go and behavior_test.go.
var _ = Describe("Custom template", func() {

	// --- access to MockData top-level fields ---

	It("template can read HeaderNote, Imports.StdImports, Options", func() {
		input := `package pkg

import "context"

type Service interface {
	Process(context.Context)
}`
		tmpl := `{{.HeaderNote}}package test
// std-imports: {{len .Imports.StdImports}}
// thread-safe: {{.Options.Async}}
type Stub struct{}
`
		out, err := GenerateMockContentWithOptions(input, Options{
			CustomTemplate: tmpl,
			AddHeaderNote:  true,
			Async:          true,
		})
		Expect(err).NotTo(HaveOccurred())
		Expect(out).To(ContainSubstring("// Code generated by MockGen. DO NOT EDIT."))
		Expect(out).To(ContainSubstring("// std-imports: 2")) // context + sync
		Expect(out).To(ContainSubstring("// thread-safe: true"))
	})

	// --- access to InterfaceData ---

	It("template can read interface Name, MockName, entry names, methods", func() {
		input := `package pkg

type Service interface {
	Send(x int) error
}`
		tmpl := `package test
{{range .Interfaces}}// Name: {{.Name}}
// MockName: {{.MockName}}
// Inspect entry: {{.InspectEntryName}} -> type {{.InspectType}}
// Config entry: {{.ConfigEntryName}} -> type {{.ConfigType}}
// Methods: {{len .Methods}}
{{end}}
type Stub struct{}
`
		out, err := GenerateMockContentWithOptions(input, Options{CustomTemplate: tmpl})
		Expect(err).NotTo(HaveOccurred())
		Expect(out).To(ContainSubstring("// Name: Service"))
		Expect(out).To(ContainSubstring("// MockName: ServiceMock"))
		Expect(out).To(ContainSubstring("// Inspect entry: Calls -> type serviceMockCalls"))
		Expect(out).To(ContainSubstring("// Config entry: On -> type serviceMockOn"))
		Expect(out).To(ContainSubstring("// Methods: 1"))
	})

	It("Inspect/Config entry names reflect the user's override", func() {
		input := `package pkg

type Service interface {
	Do()
}`
		tmpl := `package test
{{range .Interfaces}}// inspect: {{.InspectEntryName}} type: {{.InspectType}}
// config: {{.ConfigEntryName}} type: {{.ConfigType}}
{{end}}
type Stub struct{}
`
		out, err := GenerateMockContentWithOptions(input, Options{
			CustomTemplate: tmpl,
			InspectEntry:   "Inspect",
			ConfigEntry:    "Configure",
		})
		Expect(err).NotTo(HaveOccurred())
		Expect(out).To(ContainSubstring("// inspect: Inspect type: serviceMockInspect"))
		Expect(out).To(ContainSubstring("// config: Configure type: serviceMockConfigure"))
	})

	// --- access to MethodData ---

	It("template can read all MethodData type names and fields", func() {
		input := `package pkg

type Service interface {
	Send(email string) (id string, err error)
}`
		tmpl := `package test
{{range .Interfaces}}{{range .Methods}}// Name: {{.Name}}
// CallType: {{.CallType}}
// ParamType: {{.ParamType}}
// ReturnType: {{.ReturnType}}
// CfgType: {{.CfgType}}
// LogField: {{.LogField}}
// CfgField: {{.CfgField}}
// InspectMethodType: {{.InspectMethodType}}
// ConfigMethodType: {{.ConfigMethodType}}
// ParamFields: {{range .ParamFields}}{{.Name}}:{{.Type}} {{end}}
// ReturnFields: {{range .ReturnFields}}{{.Name}}:{{.Type}} {{end}}
// CfgReturnFields: {{range .CfgReturnFields}}{{.Name}}:{{.Type}} {{end}}
// Handler: {{.HandlerFieldName}} type: {{.HandlerType}}
// Returns setter: {{.ReturnsSetterName}}
{{range .IndividualReturnSetters}}// Setter: {{.MethodName}}({{.ParamType}}) -> {{.FieldName}}
{{end}}{{end}}{{end}}
type Stub struct{}
`
		out, err := GenerateMockContentWithOptions(input, Options{CustomTemplate: tmpl})
		Expect(err).NotTo(HaveOccurred())
		Expect(out).To(ContainSubstring("// Name: Send"))
		Expect(out).To(ContainSubstring("// CallType: ServiceMockSendCall"))
		Expect(out).To(ContainSubstring("// ParamType: ServiceMockSendParam"))
		Expect(out).To(ContainSubstring("// ReturnType: ServiceMockSendReturn"))
		Expect(out).To(ContainSubstring("// CfgType: serviceMockSendCfg"))
		Expect(out).To(ContainSubstring("// LogField: sendLog"))
		Expect(out).To(ContainSubstring("// CfgField: sendCfg"))
		Expect(out).To(ContainSubstring("// InspectMethodType: serviceMockSendCalls"))
		Expect(out).To(ContainSubstring("// ConfigMethodType: serviceMockSendOn"))
		Expect(out).To(ContainSubstring("// ParamFields: Email:string"))
		Expect(out).To(ContainSubstring("// ReturnFields: Id:string Err:error"))
		Expect(out).To(ContainSubstring("// CfgReturnFields: id:string err:error"))
		Expect(out).To(ContainSubstring("// Handler: handler type: func(string) (string, error)"))
		Expect(out).To(ContainSubstring("// Returns setter: Returns"))
		Expect(out).To(ContainSubstring("// Setter: ReturnsId(string) -> id"))
		Expect(out).To(ContainSubstring("// Setter: ReturnsErr(error) -> err"))
	})

	It("methods with no returns have no HandlerFieldName, no ReturnsSetterName, no IndividualReturnSetters", func() {
		input := `package pkg

type Service interface {
	Process()
}`
		tmpl := `package test

{{range .Interfaces}}{{range .Methods}}// handler={{.HandlerFieldName | printf "%q"}}
// returns-setter={{.ReturnsSetterName | printf "%q"}}
// ind-setters={{len .IndividualReturnSetters}}
{{end}}{{end}}
type Stub struct{}
`
		out, err := GenerateMockContentWithOptions(input, Options{CustomTemplate: tmpl})
		Expect(err).NotTo(HaveOccurred())
		Expect(out).To(ContainSubstring(`// handler=""`))
		Expect(out).To(ContainSubstring(`// returns-setter=""`))
		Expect(out).To(ContainSubstring("// ind-setters=0"))
	})

	// --- access to SignatureData ---

	It("template can read signature Params, Returns, ParamNames, ParamTypes, ReturnTypes", func() {
		input := `package pkg

type Service interface {
	Add(a int, b string) (int, error)
}`
		tmpl := `package test
{{range .Interfaces}}{{range .Methods}}// Params: {{.Signature.Params}}
// Returns: {{.Signature.Returns}}
// ParamNames: {{range $i, $n := .Signature.ParamNames}}{{if $i}},{{end}}{{$n}}{{end}}
// ParamTypes: {{.Signature.ParamTypes}}
// ReturnTypes: {{.Signature.ReturnTypes}}
{{end}}{{end}}
type Stub struct{}
`
		out, err := GenerateMockContentWithOptions(input, Options{CustomTemplate: tmpl})
		Expect(err).NotTo(HaveOccurred())
		Expect(out).To(ContainSubstring("// Params: a int, b string"))
		Expect(out).To(ContainSubstring("// Returns:  (int, error)"))
		Expect(out).To(ContainSubstring("// ParamNames: a,b"))
		Expect(out).To(ContainSubstring("// ParamTypes: int, string"))
		Expect(out).To(ContainSubstring("// ReturnTypes: int, error"))
	})

	// --- error paths ---

	It("returns error for malformed template", func() {
		_, err := GenerateMockContentWithOptions(`package pkg
type S interface { F() }`, Options{
			CustomTemplate: `package test
{{`,
		})
		Expect(err).To(HaveOccurred())
		Expect(err.Error()).To(ContainSubstring("template"))
	})

	It("returns error when template produces invalid Go", func() {
		_, err := GenerateMockContentWithOptions(`package pkg
type S interface { F() }`, Options{
			CustomTemplate: `package test
this is not valid go!
`,
		})
		Expect(err).To(HaveOccurred())
		Expect(err.Error()).To(ContainSubstring("formatting"))
	})

	// --- edge cases ---

	It("handles a source file with no interfaces", func() {
		input := `package pkg

type Config struct{ X int }`
		tmpl := `package test
// ifaces: {{len .Interfaces}}
type Stub struct{}
`
		out, err := GenerateMockContentWithOptions(input, Options{CustomTemplate: tmpl})
		Expect(err).NotTo(HaveOccurred())
		Expect(out).To(ContainSubstring("// ifaces: 0"))
	})

	It("handles an interface with zero methods", func() {
		input := `package pkg

type Empty interface{}`
		tmpl := `package test
{{range .Interfaces}}// methods: {{len .Methods}}
{{end}}
type Stub struct{}
`
		out, err := GenerateMockContentWithOptions(input, Options{CustomTemplate: tmpl})
		Expect(err).NotTo(HaveOccurred())
		Expect(out).To(ContainSubstring("// methods: 0"))
	})

	// --- import auto-management is default-template-only ---

	It("does not auto-add strconv/time/errors imports for custom templates", func() {
		input := `package pkg
type S interface { F() error }`
		tmpl := `package test
// no imports needed
type Stub struct{}
`
		out, err := GenerateMockContentWithOptions(input, Options{
			CustomTemplate: tmpl,
			Async:          true, // even under --async, custom templates own their imports
		})
		Expect(err).NotTo(HaveOccurred())
		Expect(out).NotTo(ContainSubstring(`"strconv"`),
			"strconv is for the default template's callIndex panic, not custom templates")
		Expect(out).NotTo(ContainSubstring(`"time"`),
			"time is for the default template's WaitFor*, not custom templates")
		Expect(out).NotTo(ContainSubstring(`"errors"`),
			"errors is for the default template's WaitFor*, not custom templates")
	})

	// --- DefaultTemplate() availability ---

	It("DefaultTemplate() returns a non-empty template usable as a starting point", func() {
		tmpl := DefaultTemplate()
		Expect(tmpl).NotTo(BeEmpty())
		Expect(tmpl).To(ContainSubstring("package test"))
	})
})
